#!/usr/bin/env node
/*
 * Turns tools/chain-source.txt (the generative chain, one paragraph per epoch,
 * each step written "what there is → what happens → what results") into
 * chain.js. Steps this simulator enacts or shows an analogue of are tagged by
 * matching the middle term, so the wording of the source stays untouched.
 */
const fs = require('fs');
const path = require('path');
const src = fs.readFileSync(path.join(__dirname, 'chain-source.txt'), 'utf8');

const EPOCHS = ['Before geometry', 'Fields to nuclei', 'Atoms to planets', 'A planet with chemistry',
  'Replicators and compartments', 'The working cell', 'A microbial world', 'The eukaryotic cell',
  'Bodies', 'Vertebrates', 'Mammals and primates', 'Hominins', 'One human'];

// middle term -> detector key in sim.js (World.prototype.analogues)
const ANALOGUE = {
  'continuing energy flows': 'flow',
  'spontaneous self-assembly': 'assemble',
  'selective acceleration of reactions': 'accel',
  'imperfect copying': 'copy',
  'differential reproduction': 'select',
  'retention within compartments': 'retain',
  'uptake of surrounding components': 'uptake',
  'division and redistribution of contents': 'divide',
  'differences in protocell reproduction': 'groupsel',
  'repair and replacement': 'repair',
  'descent with modification': 'descent',
  'adhesion or incomplete separation': 'adhere',
  'signaling and resource exchange': 'signal',
  'selection on collective performance': 'collsel',
  'developmental controls and conflict suppression': 'individ'
};

const paras = src.split(/\n\s*\n/).map(s => s.trim()).filter(Boolean);
if (paras.length !== EPOCHS.length) throw new Error('expected ' + EPOCHS.length + ' paragraphs, found ' + paras.length);
const used = new Set();
const epochs = paras.map((p, e) => {
  const steps = p.replace(/[.,]\s*$/, '').split(/,\s+/).map((piece, i) => {
    let open = null;
    piece = piece.replace(/\s*\[([^\]]+)\]\s*$/, (_, n) => { open = n; return ''; });
    const parts = piece.split(/\s*→\s*/);
    if (parts.length !== 3) throw new Error('not a three-part step: ' + piece);
    const step = { from: parts[0].charAt(0).toLowerCase() + parts[0].slice(1), via: parts[1], to: parts[2] };
    if (/^(DNA|ATP|QCD|LUCA|Homo|Earth|African)/.test(parts[0]) || /^(A growing Earth|An archaeal)/.test(parts[0])) step.from = parts[0];
    if (open) step.open = open;
    if (e === 0) step.origin = i;           // enacted by the pre-geometric prologue
    if (ANALOGUE[step.via]) { step.analogue = ANALOGUE[step.via]; used.add(step.via); }
    return step;
  });
  return { name: EPOCHS[e], steps };
});
for (const k of Object.keys(ANALOGUE)) if (!used.has(k)) throw new Error('analogue key not found in source: ' + k);

const out = '/* Generated by tools/build-chain.js from tools/chain-source.txt. Do not edit by hand. */\n' +
  "(function (root, factory) { if (typeof module === 'object' && module.exports) module.exports = factory(); else root.HolonChain = factory(); })(typeof self !== 'undefined' ? self : this, function () {\n  return " +
  JSON.stringify(epochs) + ';\n});\n';
fs.writeFileSync(path.join(__dirname, '..', 'chain.js'), out);
const n = epochs.reduce((a, e) => a + e.steps.length, 0);
console.log('chain.js: ' + epochs.length + ' epochs, ' + n + ' steps, ' + used.size + ' analogues, ' + epochs.reduce((a, e) => a + e.steps.filter(s => s.open).length, 0) + ' open questions');
